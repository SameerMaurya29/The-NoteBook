// Use a dedicated test origin. No real network requests or progress writes.
import React from 'react';
import {createRoot} from 'react-dom/client';
import {act} from 'react-dom/test-utils';
import CompanyBank from '../src/components/CompanyBank';
import PatternMatcher from '../src/components/PatternMatcher';
import ComplexityCalculator from '../src/components/ComplexityCalculator';
import SheetCard from '../src/components/SheetCard';
import {COMPANY_PROBLEMS} from '../src/content/dsa/companyProblems';
import {COMPANY_TOTALS} from '../src/content/dsa/companyTotals';
import {DSA_SHEETS} from '../src/content/dsa/sheets';
import '../src/index.css';
window.IS_REACT_ACT_ENVIRONMENT=true;
const host=document.querySelector('#root'),root=createRoot(host),checks=[];
const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(`PASS ${label}`);};
const render=async component=>{await act(async()=>root.render(component));};
const click=async element=>{if(!element)throw Error('Missing button');await act(async()=>element.click());};
const button=label=>[...host.querySelectorAll('button')].find(b=>b.textContent.includes(label));
const companies=COMPANY_PROBLEMS.filter(c=>(COMPANY_TOTALS[c.company]??0)>0||c.questions.length);
const [a,b]=companies;
const keys=[a,b].map(c=>'cp_full_v1:'+c.company),before=keys.map(k=>localStorage.getItem(k));
const originalFetch=window.fetch,originalSet=Storage.prototype.setItem;
const requests=[];
window.fetch=(url,options)=>new Promise((resolve,reject)=>requests.push({url,options,resolve,reject}));
const respond=async(index,title)=>{await act(async()=>requests[index].resolve({ok:true,headers:{get:()=> 'text/csv'},text:async()=>`Difficulty,Title,Link,Topics\nEasy,${title},https://leetcode.com/problems/two-sum/,Array`}));};
try {
 keys.forEach(k=>localStorage.removeItem(k));
 await render(<CompanyBank/>);
 check(host.textContent.includes('not unique problems'),'company totals describe occurrences, not unique questions');
 check(host.textContent.includes('date unknown'),'unknown static date disclosed');
 await click(button('Load source snapshot'));await click(button(b.company));
 check(host.querySelector('h3').textContent===b.company,'company B selected while A pending');
 check(requests[0].options.signal.aborted,'old company fetch aborted');
 await click(button('Load source snapshot'));await respond(1,'B fixture');await respond(0,'A fixture');
 check(host.textContent.includes('B fixture')&&!host.textContent.includes('A fixture'),'late A response never replaces B');
 check(host.textContent.includes('saved in this browser'),'successful cache persistence labeled');
 check(host.textContent.includes('network snapshot')&&host.textContent.includes('Fetched'),'fetch source and timestamp shown');
 await click(button('reload'));await act(async()=>requests[2].reject(Error('fixture network failure')));
 check(host.textContent.includes('fixture network failure')&&host.textContent.includes('B fixture'),'failed refresh retains visible good list');
 check(host.textContent.includes('saved in this browser'),'persistence state remains visible after failure');
 const saved=JSON.parse(localStorage.getItem(keys[1]));saved.ts=Date.now()-31*86400000;localStorage.setItem(keys[1],JSON.stringify(saved));
 await click(button(a.company));await click(button(b.company));
 check(host.textContent.includes('stale (over 30 days)')&&host.textContent.includes('B fixture'),'stale list remains available');
 await click(button(a.company));
 Storage.prototype.setItem=function(key,value){if(key.startsWith('cp_full_v1:'))throw Error('fixture quota');return originalSet.call(this,key,value);};
 await click(button('Load source snapshot'));await respond(3,'session fixture');
 check(host.textContent.includes('session only — could not save offline'),'quota failure never claims offline cache');
 Storage.prototype.setItem=originalSet;
 await render(<PatternMatcher/>);await click(button('Sorted input'));
 check(host.querySelector('.hand-stamp')?.parentElement.textContent.includes('Binary Search'),'top badge agrees with sorted-only first match');
 check(host.textContent.includes('Confirm first: Find a pair'),'unconfirmed prerequisite disclosed');
 await click(button('Find a pair'));
 check(host.querySelector('.hand-stamp')?.parentElement.textContent.includes('Two Pointers'),'sorted plus pair ranks Two Pointers');
 await click(button('clear'));await click(button('Graph / network'));await click(button('Shortest path'));
 check(!host.querySelector('.hand-stamp'),'no confirmed shortest-path claim without weight constraints');
 await click(button('Non-negative edge weights'));
 check(host.querySelector('.hand-stamp')?.parentElement.textContent.includes('Dijkstra'),'non-negative shortest path ranks Dijkstra');
 await click(button('Negative edge weights possible'));
 check(button('Non-negative edge weights').getAttribute('aria-pressed')==='false','weight selections mutually exclusive');
 check(host.querySelector('.hand-stamp')?.parentElement.textContent.includes('Bellman-Ford'),'negative weights never recommend Dijkstra/BFS');
 await render(<SheetCard sheet={DSA_SHEETS.find(s=>s.questions.some(q=>q.title==='Maximum Subarray (Kadane)'))}/>);
 check([...host.querySelectorAll('a')].find(a=>a.textContent.includes('Maximum Subarray (Kadane)'))?.getAttribute('href')==='https://leetcode.com/problems/maximum-subarray/','decorated sheet link uses explicit canonical URL');
 const unresolved=DSA_SHEETS.find(s=>s.questions.some(q=>q.url===null));await render(<SheetCard sheet={unresolved}/>);
 check([...host.querySelectorAll('a[aria-disabled="true"]')].every(a=>!a.hasAttribute('href')),'unresolved sheet links are not clickable');
 check(host.textContent.includes('link pending review'),'unresolved destination visibly labeled');
 await render(<ComplexityCalculator/>);await click(button('complexity estimator'));
 const textarea=host.querySelector('textarea');
 const type=async value=>{await act(async()=>{Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(textarea,value);textarea.dispatchEvent(new Event('input',{bubbles:true}));});};
 await type('const x = arr[0];');check((host.textContent.match(/O\(1\)/g)||[]).length>=2,'indexed read UI has constant time and auxiliary space');
 await type('def fib(n):\n    return fib(n-1)+fib(n-2)');check((host.textContent.match(/Cannot determine/g)||[]).length>=2,'unsupported recursion UI shows uncertainty for both bounds');
 await document.fonts.ready;await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
 for(let f=0;f<60&&host.scrollWidth>document.documentElement.clientWidth;f++)await new Promise(resolve=>requestAnimationFrame(resolve));
 check(host.scrollWidth<=document.documentElement.clientWidth,'expanded estimator fits viewport');
 document.querySelector('#results').textContent=checks.join('\n')+`\n${checks.length} checks passed`;
}catch(error){document.querySelector('#results').textContent=checks.join('\n')+'\nFAIL '+error.stack;}
finally {
 window.fetch=originalFetch;Storage.prototype.setItem=originalSet;
 keys.forEach((key,i)=>before[i]===null?localStorage.removeItem(key):localStorage.setItem(key,before[i]));
}
